/// Replace the one parameter in a static translated template, without reinterpreting its contents.
pub fn format_web_text(locale: Locale, english: &'static str, argument: &str) -> String {
    let template = web_text(locale, english);
    match template.split_once("{}") {
        Some((before, after)) => format!("{before}{argument}{after}"),
        None => template.into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_and_unknown_languages_use_english() {
        assert_eq!(page_locale(None), Locale::English);
        assert_eq!(page_locale(Some("unknown")), Locale::English);
        assert_eq!(
            web_text(page_locale(None), "Worker processes"),
            "Worker processes"
        );
    }

    #[test]
    fn supported_locales_preserve_translations_and_english_fallback() {
        assert_eq!(
            web_text(page_locale(Some("zh-TW")), "Worker processes"),
            "Worker 進程"
        );
        assert_eq!(
            web_text(page_locale(Some("ja")), "Address"),
            t(Locale::Japanese, UiText::Address)
        );
        assert_eq!(
            web_text(page_locale(Some("fr")), "Address"),
            t(Locale::French, UiText::Address)
        );
        assert_eq!(
            web_text(Locale::French, "Web-only fallback"),
            "Web-only fallback"
        );
    }

    #[test]
    fn localized_templates_preserve_argument_contents() {
        assert_eq!(
            format_web_text(Locale::English, "Alternate identity · {}", "key {} имя"),
            "Alternate identity · key {} имя"
        );
        assert_eq!(
            format_web_text(Locale::TraditionalChinese, "{} candidate identities", "2"),
            "存在 2 個候選身份"
        );
    }
}
