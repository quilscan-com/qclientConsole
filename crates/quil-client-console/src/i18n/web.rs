pub fn page_locale(language: Option<&str>) -> Locale {
    match language {
        Some("zh-TW") => Locale::TraditionalChinese,
        Some("ja") => Locale::Japanese,
        Some("fr") => Locale::French,
        _ => Locale::English,
    }
}

