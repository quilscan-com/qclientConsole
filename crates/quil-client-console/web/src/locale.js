const ABSENT_SEMANTIC_VALUES = new Set([
  'not set', 'not generated', 'unavailable', 'not applicable to the current identity',
  '尚未設定', '尚未產生', '不可用', '目前身份不適用',
])

export function semanticValueIsAbsent(value) {
  return value == null || ABSENT_SEMANTIC_VALUES.has(String(value).trim().toLowerCase())
}

export function semanticProofVerified(value) {
  if (value === true) return true
  const text = String(value ?? '').trim().toLowerCase()
  return ['yes', 'verified'].includes(text) || LOCALES.some(({ id }) => t(id, 'wallet.verified').toLowerCase() === text)
}

export function applyDocumentLocale(locale, document = globalThis.document) {
  const selected = LOCALES.some(({ id }) => id === locale) ? locale : 'en'
  document?.documentElement?.setAttribute('lang', selected)
  return selected
}
